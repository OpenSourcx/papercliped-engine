// Writes THIRD_PARTY_LICENSES.md: every production dependency the bridge (pnpm workspace), the engine and the sandbox provider
// install, grouped by the license each package declares, with the ones that need a closer look listed first. Run it after a
// dependency change:  node scripts/gen-notices.mjs
// The engine and the provider are installed on the host from their lockfiles (not shipped in the download), so their rows
// describe what the installer fetches; a bundled image would redistribute them.
import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";

const root = new URL("../", import.meta.url).pathname;
const groups = new Map(); // license -> Map(name -> Set(version))
const add = (license, name, version, source) => {
  const key = String(license || "UNKNOWN").trim();
  if (!groups.has(key)) groups.set(key, new Map());
  const names = groups.get(key);
  const id = `${name} (${source})`;
  if (!names.has(id)) names.set(id, new Set());
  names.get(id).add(version);
};

const pnpm = spawnSync("pnpm", ["licenses", "list", "--prod", "--json"], { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
if (pnpm.status === 0) {
  for (const [license, pkgs] of Object.entries(JSON.parse(pnpm.stdout))) for (const p of pkgs) for (const v of p.versions ?? ["?"]) add(license, p.name, v, "bridge");
} else console.error("gen-notices: pnpm licenses failed; the bridge's packages are missing from the output");

for (const [file, source] of [["engine/package-lock.json", "engine"], ["plugins/proxmox-sandbox/package-lock.json", "sandbox provider"]]) {
  const lock = JSON.parse(readFileSync(root + file, "utf8"));
  for (const [path, p] of Object.entries(lock.packages)) {
    if (!path || p.dev) continue;
    add(p.license, path.replace(/^.*node_modules\//, ""), p.version ?? "?", source);
  }
}

const attention = (license) =>
  /SEE LICENSE|UNKNOWN|GPL|MPL|UNLICENSED/i.test(license) ? (/LGPL|MPL/.test(license) ? "copyleft: notices, and the library stays replaceable" : "read the license before redistributing") : "";
const entries = [...groups.entries()].sort((a, b) => Number(!!attention(b[0])) - Number(!!attention(a[0])) || b[1].size - a[1].size);
let out = "# Third-party licenses\n\nGenerated by `node scripts/gen-notices.mjs`; do not edit by hand. These are the production dependencies of the bridge (pnpm workspace), the engine and the Proxmox sandbox provider, grouped by the license each package declares. The engine and the provider are installed on the host from their lockfiles rather than shipped in the download. See `NOTICE` for what this means.\n\n";
out += "| License | Packages | Note |\n| --- | ---: | --- |\n";
for (const [license, names] of entries) out += `| ${license} | ${names.size} | ${attention(license)} |\n`;
for (const [license, names] of entries) {
  out += `\n## ${license}\n\n`;
  const list = [...names.entries()].sort((a, b) => a[0].localeCompare(b[0])).map(([id, v]) => `${id} ${[...v].sort().join(", ")}`);
  out += list.length > 40 && !attention(license) ? `${list.length} packages (full list in the lockfiles).\n` : list.map((l) => `- ${l}`).join("\n") + "\n";
}
writeFileSync(root + "THIRD_PARTY_LICENSES.md", out);
console.log(`THIRD_PARTY_LICENSES.md: ${entries.length} licenses, ${entries.reduce((n, [, m]) => n + m.size, 0)} packages`);
