// Writes apps/console/src/data/brandIcons.ts from simple-icons (CC0), so the console ships its logos itself and never
// loads one from anywhere. Run after changing the list: node scripts/gen-brand-icons.mjs
// Brands simple-icons doesn't carry (e.g. OpenAI, Slack) are left out on purpose; the Store shows a monogram for them.
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";

const require = createRequire(new URL("../apps/console/package.json", import.meta.url));
const si = require("simple-icons");
const version = JSON.parse(readFileSync(new URL("../apps/console/node_modules/simple-icons/package.json", import.meta.url), "utf8")).version;

/** Store item id -> simple-icons export. */
const MAP = {
  anthropic: "siAnthropic", gemini: "siGooglegemini", github: "siGithub", linear: "siLinear", discord: "siDiscord", gmail: "siGmail", tailscale: "siTailscale", cloudflared: "siCloudflare",
  claude_local: "siClaude", cursor: "siCursor", cursor_cloud: "siCursor", gemini_local: "siGooglegemini", kimi_local: "siMoonshotai", opencode_local: "siOpencode",
};

const rows = Object.entries(MAP).map(([id, key]) => {
  if (!si[key]) throw new Error(`simple-icons has no ${key}`);
  return `  ${JSON.stringify(id)}: { title: ${JSON.stringify(si[key].title)}, path: ${JSON.stringify(si[key].path)} },`;
});

writeFileSync(new URL("../apps/console/src/data/brandIcons.ts", import.meta.url), `// Generated by scripts/gen-brand-icons.mjs from simple-icons ${version} (CC0 1.0). Do not edit by hand.
// The logos are trademarks of their owners; they appear only to identify the product they belong to.

export interface BrandIcon {
  title: string;
  /** A 24x24 SVG path. */
  path: string;
}

export const BRAND_ICONS: Record<string, BrandIcon> = {
${rows.join("\n")}
};
`);
console.log(`wrote ${rows.length} icons from simple-icons ${version}`);
