// Writes apps/console/src/data/brandIcons.ts so the console ships its marks itself and never loads one from anywhere.
// Sources: simple-icons (CC0 1.0) and the few single-colour marks simple-icons lacks, vendored in apps/console/brand-marks/
// from the MIT-licensed Paperclip repo (which takes them from Lobe Icons, MIT). Every mark carries its source and licence.
// Run after changing a list: node scripts/gen-brand-icons.mjs
// Brands with no openly licensed mark (Windows, Slack's shipped artwork aside) are not here; src/data/brandMarks.ts gives them a labelled generic glyph.
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";

const require = createRequire(new URL("../apps/console/package.json", import.meta.url));
const si = require("simple-icons");
const version = JSON.parse(readFileSync(new URL("../apps/console/node_modules/simple-icons/package.json", import.meta.url), "utf8")).version;

/** Mark id -> simple-icons export. Ids are Store item ids, provider slugs and library ids. */
const SIMPLE = {
  notion: "siNotion", vercel: "siVercel", anthropic: "siAnthropic", gemini: "siGooglegemini", github: "siGithub", linear: "siLinear", discord: "siDiscord", gmail: "siGmail", tailscale: "siTailscale", cloudflared: "siCloudflare", cloudflare: "siCloudflare",
  claude_local: "siClaude", cursor: "siCursor", cursor_cloud: "siCursor", gemini_local: "siGooglegemini", kimi_local: "siMoonshotai", opencode_local: "siOpencode",
  // Model providers
  mistral: "siMistralai", deepseek: "siDeepseek", ollama: "siOllama", openrouter: "siOpenrouter", huggingface: "siHuggingface", perplexity: "siPerplexity",
  // Operating systems, and the Fedora Project's VirtIO drivers
  debian: "siDebian", "ubuntu-lts": "siUbuntu", alpine: "siAlpinelinux", "rocky-9": "siRockylinux", "alma-9": "siAlmalinux", arch: "siArchlinux", "virtio-win": "siFedora",
  telegram: "siTelegram", whatsapp: "siWhatsapp", signal: "siSignal", matrix: "siMatrix",
  fedora: "siFedora", opensuse: "siOpensuse", centos: "siCentos", proxmox: "siProxmox",
  // Apps that ship as ready-made templates
  nextcloud: "siNextcloud", gitea: "siGitea", wordpress: "siWordpress",
};
/** Mark id -> single-path SVG vendored in apps/console/brand-marks/ (source: paperclipai/paperclip ui/public/brands, MIT; artwork from Lobe Icons, MIT). */
const VENDORED = {
  openai: "openai.svg", codex_local: "openai.svg", xai: "xai.svg", grok_local: "xai.svg", pi_local: "pi.svg", hermes_local: "hermesagent.svg", hermes_gateway: "hermesagent.svg",
};
const VENDOR_SRC = "paperclipai/paperclip@cbf811c ui/public/brands (MIT, Copyright (c) 2025 Paperclip AI); artwork from Lobe Icons (MIT, Copyright (c) 2023 LobeHub)";

const row = (id, o) => `  ${JSON.stringify(id)}: ${JSON.stringify(o)},`;
const rows = [];
for (const [id, key] of Object.entries(SIMPLE)) {
  if (!si[key]) throw new Error(`simple-icons has no ${key}`);
  rows.push(row(id, { title: si[key].title, path: si[key].path, source: `simple-icons ${version}`, license: "CC0-1.0" }));
}
for (const [id, file] of Object.entries(VENDORED)) {
  const svg = readFileSync(new URL(`../apps/console/brand-marks/${file}`, import.meta.url), "utf8");
  if (/<(script|image|foreignObject|style)\b|\son[a-z]+=|href=/i.test(svg)) throw new Error(`${file}: active or external content`);
  const path = [...svg.matchAll(/<path\b[^>]*?\sd="([^"]+)"/g)].map((m) => m[1]).join(" ");
  const title = svg.match(/<title>([^<]+)<\/title>/)?.[1];
  if (!path || !title) throw new Error(`${file}: no path or title`);
  rows.push(row(id, { title, path, evenodd: true, source: `${file}: ${VENDOR_SRC}`, license: "MIT" }));
}

writeFileSync(new URL("../apps/console/src/data/brandIcons.ts", import.meta.url), `// Generated by scripts/gen-brand-icons.mjs from simple-icons ${version} (CC0 1.0) and apps/console/brand-marks/ (MIT). Do not edit by hand.
// The marks are trademarks of their owners; they appear only to identify the product they belong to.

export interface BrandIcon {
  title: string;
  /** A 24x24 SVG path. */
  path: string;
  /** Fill with the even-odd rule (the vendored marks are drawn for it). */
  evenodd?: boolean;
  /** Where the artwork came from, and its licence. */
  source: string;
  license: "CC0-1.0" | "MIT";
}

export const BRAND_ICONS: Record<string, BrandIcon> = {
${rows.join("\n")}
};
`);
console.log(`wrote ${rows.length} marks`);
