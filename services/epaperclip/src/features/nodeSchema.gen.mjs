// Regenerates nodeSchema.ts from the Proxmox VE API viewer data, so the forms and the strict validation come from
// Proxmox's own parameter definitions instead of being guessed.
//
//   curl -sS https://pve.proxmox.com/pve-docs/api-viewer/apidoc.js -o apidoc.js
//   node services/epaperclip/src/features/nodeSchema.gen.mjs apidoc.js > services/epaperclip/src/features/nodeSchema.ts
//
// Only the endpoints the node and datacenter screens write to are included. The output is plain data.
import { readFileSync } from "node:fs";

const src = readFileSync(process.argv[2], "utf8");
const start = src.indexOf("const apiSchema = ") + "const apiSchema = ".length;
const api = JSON.parse(src.slice(start, src.indexOf("\n]\n;", start) + 2));
const find = (nodes, path) => {
  for (const n of nodes) {
    if (n.path === path) return n;
    const r = n.children && find(n.children, path);
    if (r) return r;
  }
};
const params = (path, method) => {
  const n = find(api, path);
  if (!n || !n.info[method]) throw new Error(`no ${method} ${path}`);
  return n.info[method].parameters.properties;
};

const SECRET = new Set(["token", "password", "secret", "eab-hmac-key", "otel-headers", "data"]);
// Perl-style inline flags in Proxmox patterns: (?^i:x) is "x, case-insensitively".
const jsPattern = (p) => {
  if (typeof p !== "string") return undefined;
  let flags = "";
  let out = p.replace(/\(\?\^i:/g, () => ((flags = "i"), "(?:"));
  if (/\(\?\^/.test(out) || /\(\?[a-z]*[-^]/.test(out)) return undefined;
  try {
    new RegExp(`^(?:${out})$`, flags);
  } catch {
    return undefined;
  }
  return { source: out, flags };
};

function field(name, p) {
  const f = { description: String(p.description ?? "").split("\n")[0].slice(0, 300) };
  if (p.type === "array") {
    f.type = "array";
    f.items = field(name, p.items ?? { type: "string" });
    return f;
  }
  f.type = p.type === "number" ? "number" : p.type;
  if (p.enum) f.enum = p.enum;
  // Top-level parameters say minimum/maximum; the fields inside property strings say min/max.
  const lo = p.minimum ?? p.min;
  const hi = p.maximum ?? p.max;
  if (lo !== undefined) f.min = Number(lo);
  if (hi !== undefined) f.max = Number(hi);
  if (p.maxLength !== undefined) f.maxLength = p.maxLength;
  if (p.default !== undefined) f.default = p.default;
  if (typeof p.format === "string") f.format = p.format;
  const pat = jsPattern(p.pattern);
  if (pat) f.pattern = pat;
  if (SECRET.has(name)) f.secret = true;
  if (p.format && typeof p.format === "object") {
    f.props = {};
    for (const [k, v] of Object.entries(p.format)) {
      const sub = field(k, v);
      if (!v.optional) sub.required = true;
      if (v.default_key) sub.defaultKey = true;
      f.props[k] = sub;
    }
  }
  return f;
}

function group(path, method, { skip = [], keep } = {}) {
  const out = {};
  for (const [name, p] of Object.entries(params(path, method))) {
    if (["delete", "digest", "node", "id", "name"].includes(name) || skip.includes(name)) continue;
    if (keep && !keep.includes(name)) continue;
    const f = field(name, p);
    if (!p.optional) f.required = true;
    out[name] = f;
  }
  return out;
}

const schemas = {
  clusterOptions: group("/cluster/options", "PUT", { skip: ["migration_unsecure", "u2f", "webauthn", "notify", "consent-text"] }),
  sendmail: group("/cluster/notifications/endpoints/sendmail", "POST"),
  gotify: group("/cluster/notifications/endpoints/gotify", "POST"),
  smtp: group("/cluster/notifications/endpoints/smtp", "POST"),
  webhook: group("/cluster/notifications/endpoints/webhook", "POST"),
  matcher: group("/cluster/notifications/matchers", "POST"),
  metricServer: group("/cluster/metrics/server/{id}", "POST"),
  acmePlugin: group("/cluster/acme/plugins", "POST", { skip: ["type"] }),
};

console.log(`// GENERATED by nodeSchema.gen.mjs from the Proxmox VE API viewer. Do not edit by hand.
// Proxmox's own parameter definitions for the datacenter settings the node screens write.

export interface FieldSchema {
  type: "string" | "integer" | "number" | "boolean" | "array";
  description: string;
  required?: boolean;
  enum?: string[];
  min?: number;
  max?: number;
  maxLength?: number;
  default?: string | number | boolean;
  format?: string;
  pattern?: { source: string; flags: string };
  secret?: boolean;
  items?: FieldSchema;
  /** A Proxmox property string: key=value pairs joined by commas. */
  props?: Record<string, FieldSchema & { defaultKey?: boolean }>;
}
export type Schema = Record<string, FieldSchema>;

export const SCHEMAS: Record<"clusterOptions" | "sendmail" | "gotify" | "smtp" | "webhook" | "matcher" | "metricServer" | "acmePlugin", Schema> = ${JSON.stringify(schemas, null, 1)};
`);
